async function main() {
  console.log('🚀 Updating Nitsuh Cafe Menu with curated high-def images and descriptions...');

  for (const catData of nitsuhMenuData) {
    const category = await prisma.category.upsert({
      where: { name: catData.name },
      update: {
        displayOrder: catData.displayOrder,
        iconName: catData.iconName,
        badgeColor: catData.badgeColor,
        isActive: true,
      },
      create: {
        name: catData.name,
        displayOrder: catData.displayOrder,
        iconName: catData.iconName,
        badgeColor: catData.badgeColor,
        isActive: true,
      },
    });

    for (const itemData of catData.items) {
      const existing = await prisma.menuItem.findFirst({
        where: { name: itemData.name },
      });

      if (existing) {
        await prisma.menuItem.update({
          where: { id: existing.id },
          data: {
            categoryId: category.id,
            description: itemData.description,
            price: itemData.price,
            prepSection: itemData.prepSection,
            isDirectSale: itemData.isDirectSale ?? false,
            imageUrl: itemData.imageUrl,
            isAvailable: true,
          },
        });
      } else {
        await prisma.menuItem.create({
          data: {
            name: itemData.name,
            categoryId: category.id,
            description: itemData.description,
            price: itemData.price,
            prepSection: itemData.prepSection,
            isDirectSale: itemData.isDirectSale ?? false,
            imageUrl: itemData.imageUrl,
            isAvailable: true,
          },
        });
      }
    }
  }

  console.log('✅ Menu images and descriptions updated successfully!');
}

main()
  .catch((e) => {
    console.error('❌ Error updating menu images:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
